/**
 * Cookie formatting / import helpers. Pure functions on chrome.cookies rows.
 * Unit tested in tests/core/cookie.test.js
 */

/**
 * JSON export (pretty): the fields that round-trip through cookies.set.
 */
export function cookiesToJson(cookies) {
  const data = (cookies || []).map((c) => ({
    name: c.name,
    value: c.value,
    domain: c.domain,
    path: c.path || '/',
    secure: !!c.secure,
    httpOnly: !!c.httpOnly,
    hostOnly: !!(c.hostOnly ?? !String(c.domain || '').startsWith('.')),
    sameSite: c.sameSite || 'unspecified',
    expirationDate: c.expirationDate ?? null,
    storeId: c.storeId
  }))
  return JSON.stringify(data, null, 2)
}

/**
 * Netscape cookies.txt export (curl/wget compatible).
 */
export function cookiesToNetscape(cookies) {
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by dev-quick-assistant. This is a generated file! Do not edit.',
    ''
  ]
  for (const c of cookies || []) {
    const domain = String(c.domain || '')
    const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE'
    const secure = c.secure ? 'TRUE' : 'FALSE'
    const expires = c.expirationDate ? String(Math.floor(c.expirationDate)) : '0'
    const name = String(c.name ?? '')
    const value = String(c.value ?? '')
    let line = [domain, includeSub, c.path || '/', secure, expires, name, value].join('\t')
    if (c.httpOnly) line = '#HttpOnly_' + line
    lines.push(line)
  }
  return lines.join('\n') + '\n'
}

/** Cookie header string: "a=1; b=2". */
export function cookiesToHeader(cookies) {
  return (cookies || []).map((c) => `${c.name}=${c.value}`).join('; ')
}

/**
 * Parse an imported JSON array of cookies (lenient field validation).
 * @returns {{ok:true, cookies:Array} | {ok:false, error:string}}
 */
export function parseImportCookies(text) {
  let data
  try {
    data = JSON.parse(String(text ?? ''))
  } catch (e) {
    return { ok: false, error: String((e && e.message) || e) }
  }
  if (!Array.isArray(data)) return { ok: false, error: 'not-array' }
  const cookies = []
  for (const item of data) {
    if (!item || typeof item !== 'object') continue
    if (typeof item.name !== 'string' || !item.name) continue
    if (typeof item.domain !== 'string' || !item.domain) continue
    cookies.push({
      name: item.name,
      value: typeof item.value === 'string' ? item.value : String(item.value ?? ''),
      domain: item.domain,
      path: typeof item.path === 'string' && item.path ? item.path : '/',
      secure: !!item.secure,
      httpOnly: !!item.httpOnly,
      hostOnly: item.hostOnly != null ? !!item.hostOnly : !item.domain.startsWith('.'),
      sameSite: item.sameSite || 'unspecified',
      expirationDate: Number.isFinite(item.expirationDate) ? item.expirationDate : null
    })
  }
  return { ok: true, cookies }
}

/**
 * Build chrome.cookies.set params from a cookie row.
 * hostOnly cookies must NOT pass domain (otherwise they become domain cookies).
 */
export function cookieToSetParams(c, origin) {
  const domain = String(c.domain || '')
  const hostOnly = c.hostOnly != null ? !!c.hostOnly : !domain.startsWith('.')
  const scheme = c.secure ? 'https' : 'http'
  const host = domain.startsWith('.') ? domain.slice(1) : domain
  const url = origin || `${scheme}://${host}${c.path || '/'}`
  const params = {
    url,
    name: c.name,
    value: c.value,
    path: c.path || '/'
  }
  if (!hostOnly && domain) params.domain = domain
  if (c.secure) params.secure = true
  if (c.httpOnly) params.httpOnly = true
  if (c.expirationDate) params.expirationDate = Math.floor(c.expirationDate)
  if (c.sameSite && c.sameSite !== 'unspecified') params.sameSite = c.sameSite
  return params
}

export function formatExpiry(c) {
  if (!c.expirationDate) return 'session'
  try {
    return new Date(c.expirationDate * 1000).toISOString().replace('T', ' ').slice(0, 19) + ' UTC'
  } catch {
    return String(c.expirationDate)
  }
}
