function resolveLocale() {
  const pref = settings.locale
  if (pref === 'zh' || pref === 'en') return pref
  const lang = (typeof navigator !== 'undefined' && navigator.language) || 'zh'
  return lang.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/**
 * Translate a dotted key, with {var} interpolation.
 */
export function t(key, vars) {
  const loc = resolveLocale()
  let val = lookup(MESSAGES[loc], key)
  if (val == null) val = lookup(MESSAGES[loc === 'zh' ? 'en' : 'zh'], key)
  if (val == null) return key
  if (vars) {
    for (const k of Object.keys(vars)) {
      val = val.replaceAll(`{${k}}`, String(vars[k]))
    }
  }
  return val
}

function lookup(obj, path) {
  let cur = obj
  for (const seg of path.split('.')) {
    if (cur == null || typeof cur !== 'object') return undefined
    cur = cur[seg]
  }
  return typeof cur === 'string' ? cur : undefined
}
